"""Assembly (brief §7.5): per-shot clips + mix -> episode.mp4 with sidecar and burned-in subtitles.

Also builds the animatic baseline (keyframes + pan/zoom + the SAME audio and cuts), so A/B isolates the video stage.
"""
from __future__ import annotations

from pathlib import Path

import pysubs2

from src.common.config import CFG
from src.common.io import ffmpeg, log, media_duration, write_json
from src.generate.audio import frames_of, line_schedule, timeline
from src.generate.video import OUT_FPS, still_clip

FINAL_W, FINAL_H = 1280, 720


def write_subs(shots: list[dict], out: Path) -> Path:
    subs = pysubs2.SSAFile()
    subs.info["PlayResX"], subs.info["PlayResY"] = str(FINAL_W), str(FINAL_H)
    subs.styles["Default"] = pysubs2.SSAStyle(fontname="DejaVu Sans", fontsize=38, bold=True, outline=2.5, shadow=0.5, marginv=36)
    subs.styles["Notebook"] = pysubs2.SSAStyle(fontname="DejaVu Sans", fontsize=40, italic=True, outline=2.5, shadow=0.5,
                                               alignment=pysubs2.Alignment.TOP_CENTER, marginv=40,
                                               primarycolor=pysubs2.Color(255, 250, 205))
    subs.styles["Thought"] = pysubs2.SSAStyle(fontname="DejaVu Sans", fontsize=36, italic=True, outline=2.5, shadow=0.5, marginv=36)
    for ln in line_schedule(shots):
        text = (ln.get("text") or "").strip()
        if not text or ln["kind"] == "sfx_text":
            continue
        style = {"notebook": "Notebook", "thought": "Thought", "narration": "Thought"}.get(ln["kind"], "Default")
        if ln["kind"] == "notebook":
            text = "✎ " + text
        subs.append(pysubs2.SSAEvent(start=int(ln["start"] * 1000), end=int(max(ln["end"], ln["start"] + 0.8) * 1000), text=text, style=style))
    out.parent.mkdir(parents=True, exist_ok=True)
    subs.save(str(out))
    return out


def concat(clips: list[Path], out: Path, scale: bool = True) -> Path:
    lst = out.with_suffix(".txt")
    lst.write_text("".join(f"file '{c}'\n" for c in clips))
    vf = f"scale={FINAL_W}:{FINAL_H}:flags=lanczos,setsar=1,format=yuv420p" if scale else "format=yuv420p"
    ffmpeg("-f", "concat", "-safe", "0", "-i", str(lst), "-vf", vf, "-r", "24000/1001", "-c:v", "libx264", "-preset", "medium",
           "-crf", "17", "-an", str(out))
    return out


def mux(video: Path, audio: Path | None, subs: Path | None, out: Path, burn: bool = True) -> Path:
    args = ["-i", str(video)]
    if audio and audio.exists():
        args += ["-i", str(audio)]
    vf = []
    if burn and subs and subs.exists():
        esc = str(subs).replace("\\", "\\\\").replace(":", "\\:").replace("'", "\\'")
        vf = ["-vf", f"ass='{esc}'"]
    args += vf + ["-c:v", "libx264", "-preset", "medium", "-crf", "18", "-pix_fmt", "yuv420p"]
    if audio and audio.exists():
        args += ["-c:a", "aac", "-b:a", "192k", "-shortest"]
    ffmpeg(*args, "-movflags", "+faststart", str(out))
    return out


def assemble(run_dir: Path, shots: list[dict], *, variant: str = "wan", burn_subs: bool = True) -> Path:
    """variant 'wan' uses shots/<id>/clip.mp4; 'animatic' uses shots/<id>/animatic.mp4 (built on demand)."""
    clips, missing = [], []
    for s in shots:
        sdir = run_dir / "shots" / s["shot_id"]
        if variant == "animatic":
            c = sdir / "animatic.mp4"
            want = frames_of(s["duration"]) / OUT_FPS
            stale = c.exists() and (sdir / "kf.png").exists() and (sdir / "kf.png").stat().st_mtime > c.stat().st_mtime
            if not c.exists() or stale or abs(media_duration(c) - want) > 0.06:      # stale: keyframe regenerated by a repair
                still_clip(sdir / "kf.png", c, s["duration"], s.get("camera", "static"))
        else:
            c = sdir / "clip.mp4"
            want = frames_of(s["duration"]) / OUT_FPS
            if not c.exists():
                missing.append(s["shot_id"])
                c = sdir / "fallback.mp4"          # never leave a hole in the timeline
                still_clip(sdir / "kf.png", c, s["duration"], s.get("camera", "static"))
            elif abs(media_duration(c) - want) > 0.06:
                # duration changed after the clip was rendered (e.g. TTS re-fit): re-time by trimming / freezing the last frame
                fixed = sdir / "clip_fit.mp4"
                ffmpeg("-i", str(c), "-vf", f"tpad=stop_mode=clone:stop_duration={max(0.0, want - media_duration(c)) + 0.1:.3f}",
                       "-frames:v", str(frames_of(s["duration"])), "-r", "24000/1001", "-c:v", "libx264", "-crf", "14", "-an", str(fixed))
                c = fixed
        clips.append(c)
    out_dir = run_dir if variant == "wan" else run_dir / "animatic"
    out_dir.mkdir(parents=True, exist_ok=True)
    video = concat(clips, out_dir / "video_only.mp4")
    subs = write_subs(shots, run_dir / "episode.ass")
    audio = run_dir / "audio" / "mix.wav"
    final = mux(video, audio, subs, out_dir / "episode.mp4", burn=burn_subs)
    write_json(out_dir / "assembly.json", {"variant": variant, "n_shots": len(shots), "missing_clips": missing,
                                           "duration": media_duration(final), "timeline": timeline(shots)})
    log(f"assembled {variant}: {final} ({media_duration(final):.1f}s, {len(missing)} fallback shots)")
    return final
