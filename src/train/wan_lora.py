"""Wan 2.2 A14B I2V LoRA tooling (musubi-tuner @ pinned commit): dataset config, caching, local smoke test, upload.

Run with the musubi venv (after `. scripts/env.sh`):

    MP=$KOMI_WORK/venvs/musubi/bin/python
    $MP -m src.train.wan_lora make-smoke-set                      # 8 clips from episode 1 (placeholder captions)
    $MP -m src.train.wan_lora make-config --clips <dir> --name full_480p
    $MP -m src.train.wan_lora cache --config <toml>               # VAE latents (I2V) + T5 outputs, local GPU
    $MP -m src.train.wan_lora smoke --expert both                 # ~60 steps per expert on the 24 GB card
    $MP -m src.train.wan_lora upload-cache --config <toml>        # tar shards -> PRIVATE dataset repo
    $MP -m src.train.wan_lora pull --run <run_name>               # final LoRA -> models/comfy/loras/

Dataset contract: <clips>/<clip_id>.mp4 (832x480, 16 fps, exactly 81 frames) + <clip_id>.txt (caption starting with the
trigger token). Train episodes are 1-21 only; ids containing ep22-ep24 are refused.
"""
from __future__ import annotations

import argparse
import json
import os
import subprocess
import sys
from pathlib import Path

from . import common as C

ARCH = "wan"
EXPERTS = {
    "high": {"config": "train_wan22_i2v_high.toml", "dit": "wan_dit_high", "min_t": 900, "max_t": 1000},
    "low": {"config": "train_wan22_i2v_low.toml", "dit": "wan_dit_low", "min_t": 0, "max_t": 900},
}


# ----------------------------------------------------------------------------- dataset config

def parse_res(s: str) -> tuple[int, int]:
    w, h = (int(x) for x in s.lower().split("x"))
    if w % 16 or h % 16:
        raise SystemExit(f"resolution {s}: width and height must be multiples of 16")
    return w, h


def variant_name(w: int, h: int, frames: int) -> str:
    return f"{w}x{h}_f{frames}"


def dataset_name(clips: Path) -> str:
    """Name of the dataset in the Hub cache repo: data/processed/train/wan/clips -> full, .../wan_smoke/clips -> wan_smoke."""
    parent = clips.resolve().parent.name
    return "full" if parent == "wan" else parent


def default_config_path(clips: Path, w: int, h: int, frames: int) -> Path:
    return clips.parent / "configs" / f"wan_{variant_name(w, h, frames)}.toml"


def validate_clips(clips: Path, frames: int, probe: int) -> dict:
    """Check the dataset contract. `probe` = number of clips to ffprobe (0 = none, -1 = all)."""
    vids = sorted(clips.glob("*.mp4"))
    if not vids:
        raise SystemExit(f"no .mp4 clips in {clips}")
    C.assert_train_split([v.name for v in vids])
    trigger = C.infra()["data"]["trigger"]
    missing = [v.name for v in vids if not v.with_suffix(".txt").exists()]
    if missing:
        raise SystemExit(f"{len(missing)} clips without caption .txt, e.g. {missing[:3]}")
    no_trigger = [v.name for v in vids if not v.with_suffix(".txt").read_text(encoding="utf-8").lstrip().startswith(trigger)]
    if no_trigger:
        raise SystemExit(f"{len(no_trigger)} captions do not start with the trigger token '{trigger}', e.g. {no_trigger[:3]}")
    bad = []
    sample = vids if probe < 0 else vids[:: max(1, len(vids) // probe)][:probe] if probe else []
    for v in sample:
        out = subprocess.run([str(C.FFPROBE), "-v", "error", "-select_streams", "v:0", "-count_frames", "-show_entries",
                              "stream=width,height,r_frame_rate,nb_read_frames", "-of", "json", str(v)],
                             capture_output=True, text=True)
        try:
            st = json.loads(out.stdout)["streams"][0]
            num, den = st["r_frame_rate"].split("/")
            fps = float(num) / float(den)
            n = int(st["nb_read_frames"])
            if n < frames or abs(fps - 16.0) > 0.01:
                bad.append(f"{v.name}: {st['width']}x{st['height']} {fps:.3f} fps {n} frames")
        except Exception as e:  # noqa: BLE001
            bad.append(f"{v.name}: ffprobe failed ({e})")
    if bad:
        raise SystemExit("clips violating the contract (need >= %d frames @ 16 fps):\n  " % frames + "\n  ".join(bad[:10]))
    return {"n_clips": len(vids), "probed": len(sample)}


def cmd_make_config(a) -> Path:
    clips = Path(a.clips).resolve()
    w, h = parse_res(a.resolution)
    if (a.frames - 1) % 4:
        raise SystemExit("frames must be N*4+1 (e.g. 81, 33)")
    stats = validate_clips(clips, a.frames, a.probe)
    cache_dir = Path(a.cache_dir).resolve() if a.cache_dir else clips.parent / "cache" / f"wan_{variant_name(w, h, a.frames)}"
    out = Path(a.out).resolve() if a.out else default_config_path(clips, w, h, a.frames)
    cfg = {
        "_comment": (f"musubi-tuner dataset config, generated by src/train/wan_lora.py make-config\n"
                     f"clips={clips} ({stats['n_clips']} clips) resolution={w}x{h} frames={a.frames}\n"
                     f"The cache directory must not be shared between datasets/variants."),
        "general": {"resolution": [w, h], "caption_extension": ".txt", "batch_size": a.batch_size,
                    "enable_bucket": False, "bucket_no_upscale": False},
        "datasets": [{"video_directory": str(clips), "cache_directory": str(cache_dir), "target_frames": [a.frames],
                      "frame_extraction": "head", "num_repeats": a.repeats}],
    }
    C.write_text(out, C.toml_dump(cfg))
    cache_dir.mkdir(parents=True, exist_ok=True)
    C.log(f"wrote {out}  ({stats['n_clips']} clips, cache -> {cache_dir})")
    return out


def load_dataset_config(path: Path) -> dict:
    cfg = C.read_toml(path)
    ds = cfg["datasets"][0]
    w, h = cfg["general"]["resolution"]
    return {"path": path, "clips": Path(ds["video_directory"]), "cache": Path(ds["cache_directory"]),
            "w": w, "h": h, "frames": ds["target_frames"][0], "batch_size": cfg["general"].get("batch_size", 1)}


# ----------------------------------------------------------------------------- smoke set

def cmd_make_smoke_set(a) -> None:
    """Cut N 81-frame clips (832x480 @ 16 fps) from a TRAIN episode proxy. Stays on this machine."""
    C.assert_train_split([f"ep{a.episode:02d}"])
    src = C.WORK / "data" / "interim" / "anime" / f"ep{a.episode:02d}" / "proxy.mp4"
    if not src.exists():
        raise SystemExit(f"missing {src}")
    out = Path(a.out) if a.out else Path(C.infra()["data"]["wan_smoke"])
    clips = out / "clips"
    clips.mkdir(parents=True, exist_ok=True)
    trigger = C.infra()["data"]["trigger"]
    dur = float(subprocess.run([str(C.FFPROBE), "-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", str(src)],
                               capture_output=True, text=True).stdout.strip())
    # skip the first 3 min (cold open / OP) and the last 3 min (ED / preview)
    starts = [180 + i * (dur - 360 - 6) / max(1, a.n - 1) for i in range(a.n)]
    for i, t in enumerate(starts):
        cid = f"ep{a.episode:02d}_smoke{i:02d}"
        mp4 = clips / f"{cid}.mp4"
        if not mp4.exists():
            C.run([str(C.FFMPEG), "-v", "error", "-y", "-ss", f"{t:.3f}", "-i", str(src), "-an",
                   "-vf", "fps=16,scale=-2:480,crop=832:480", "-frames:v", "81",
                   "-c:v", "libx264", "-crf", "14", "-preset", "medium", "-pix_fmt", "yuv420p", str(mp4)])
        C.write_text(clips / f"{cid}.txt",
                     f"{trigger}, anime style scene from a high school slice-of-life comedy, placeholder caption {i} for the smoke test\n")
    C.log(f"smoke set: {len(starts)} clips in {clips}")


# ----------------------------------------------------------------------------- caching

def cmd_cache(a) -> None:
    ds = load_dataset_config(Path(a.config))
    w = C.infra()["local_weights"]
    log_file = ds["cache"].parent / "logs" / f"cache_{ds['cache'].name}.log"
    py = C.musubi_python()
    common_args = ["--dataset_config", str(ds["path"])] + (["--skip_existing"] if a.skip_existing else [])
    if a.device == "cpu":
        # GPU stays untouched (CUDA hidden); float32 VAE and T5. Slow: only for small sets.
        env = {**C.cpu_env(), "PYTHONPATH": str(C.REPO)}
        C.run([py, "-m", "src.train.musubi_cpu", "wan_cache_latents", *common_args, "--vae", w["wan_vae"], "--i2v",
               "--device", "cpu", "--vae_dtype", "float32", "--num_workers", "2"], log_file=log_file, env=env, cwd=str(C.REPO))
        C.run([py, "-m", "src.train.musubi_cpu", "wan_cache_text_encoder_outputs", *common_args, "--t5", w["wan_t5"],
               "--device", "cpu", "--batch_size", "1", "--num_workers", "2"], log_file=log_file, env=env, cwd=str(C.REPO))
    else:
        only = getattr(a, "only", "both")
        if only in ("both", "latents"):
            C.run([*C.gpu_prefix(a.need_gb), py, C.musubi_script("wan_cache_latents.py"), *common_args, "--vae", w["wan_vae"],
                   "--i2v", "--batch_size", str(a.vae_batch_size), *(["--vae_cache_cpu"] if getattr(a, "vae_cache_cpu", False) else [])],
                  log_file=log_file)
        if only in ("both", "te"):
            C.run([*C.gpu_prefix(a.need_gb), py, C.musubi_script("wan_cache_text_encoder_outputs.py"), *common_args,
                   "--t5", w["wan_t5"], "--batch_size", str(a.te_batch_size)], log_file=log_file)
        if only != "both":
            C.log(f"cache --only {only}: done")
            return
    files = C.list_cache_files(ds["cache"], ARCH)
    n_lat = sum(1 for p in files if not p.name.endswith("_te.safetensors"))
    n_te = len(files) - n_lat
    n_clips = len(list(ds["clips"].glob("*.mp4")))
    total = sum(p.stat().st_size for p in files)
    C.log(f"cache: {n_lat} latent + {n_te} text-encoder files for {n_clips} clips, {total / 1e6:.1f} MB in {ds['cache']}")
    if n_lat != n_clips or n_te != n_clips:
        raise SystemExit("cache is incomplete (see the log above); re-run `cache`")


# ----------------------------------------------------------------------------- local smoke test

def smoke_config(a) -> Path:
    """Reduced-size dataset config over the smoke clips (fits 24 GB with fp8 + block swap)."""
    if a.config:
        return Path(a.config)
    clips = Path(C.infra()["data"]["wan_smoke"]) / "clips"
    ns = argparse.Namespace(clips=str(clips), resolution=a.resolution, frames=a.frames, cache_dir=None, out=None,
                            batch_size=1, repeats=1, probe=0)
    return cmd_make_config(ns)


def train_command(expert: str, dataset_config: Path, out_dir: Path, name: str, steps: int, save_every: int,
                  extra: list[str], dit: str | None = None) -> list[str]:
    e = EXPERTS[expert]
    w = C.infra()["local_weights"]
    return [*C.accelerate_launch("fp16"), C.musubi_script("wan_train_network.py"),
            "--config_file", str(C.REPO / "configs" / e["config"]),
            "--dit", dit or w[e["dit"]], "--dataset_config", str(dataset_config),
            "--output_dir", str(out_dir), "--output_name", name, "--logging_dir", str(out_dir / "tb"),
            "--max_train_steps", str(steps), "--save_every_n_steps", str(save_every), "--save_state", *extra]


def cmd_smoke(a) -> None:
    cfg_path = smoke_config(a)
    ds = load_dataset_config(cfg_path)
    experts = ["high", "low"] if a.expert == "both" else [a.expert]
    w = C.infra()["local_weights"]
    for e in experts:
        if not Path(w[EXPERTS[e]["dit"]]).exists():
            raise SystemExit(f"missing DiT for the {e}-noise expert: {w[EXPERTS[e]['dit']]}")
    if not C.list_cache_files(ds["cache"], ARCH) or a.recache:
        cmd_cache(argparse.Namespace(config=str(cfg_path), device=a.cache_device, need_gb=14, skip_existing=True,
                                     vae_batch_size=1, te_batch_size=8))
    # 24 GB settings: fp8 (scaled) base weights + block swap; the HF job uses none of these.
    extra = ["--fp8_base", "--fp8_scaled", "--blocks_to_swap", str(a.blocks_to_swap), "--lr_warmup_steps", "10"]
    results = {}
    for e in experts:
        name = f"smoke_wan22_i2v_{e}"
        out_dir = C.RUNS / "train" / name
        out_dir.mkdir(parents=True, exist_ok=True)
        log_file = out_dir / "train.log"
        if log_file.exists():
            log_file.unlink()
        cmd = train_command(e, cfg_path, out_dir, name, a.steps, max(1, a.steps // 2), extra)
        rc = C.run([*C.gpu_prefix(a.need_gb), sys.executable, "-m", "src.train.vram_watch", str(out_dir / "vram.json"), "--", *cmd],
                   log_file=log_file, check=False, cwd=str(C.REPO), env={"PYTHONPATH": str(C.REPO)})
        res = summarize_run(log_file, out_dir, name, rc, e, ds, a.blocks_to_swap)
        results[e] = res
        C.write_text(out_dir / "smoke_result.json", json.dumps(res, indent=1))
        C.log(f"smoke {e}: {json.dumps(res)}")
        if rc != 0 or not res["ok"]:
            raise SystemExit(f"smoke test FAILED for the {e}-noise expert (log: {log_file})")
    C.log("smoke test passed: " + json.dumps({k: {x: v[x] for x in ('s_per_step', 'last_avr_loss', 'vram_peak_gb')} for k, v in results.items()}))


def summarize_run(log_file: Path, out_dir: Path, name: str, rc: int, expert: str, ds: dict, blocks_to_swap: int) -> dict:
    from infra.hf_jobs.logparse import parse_progress  # shared tqdm parser (also used by the HF monitor)

    pts = parse_progress(log_file.read_text(errors="replace"))
    steady = [p["s_per_step"] for p in pts if p["step"] >= 3 and p.get("s_per_step")]
    vram = {}
    try:
        vram = json.loads((out_dir / "vram.json").read_text())
    except Exception:  # noqa: BLE001
        pass
    final = out_dir / f"{name}.safetensors"
    losses = [p["avr_loss"] for p in pts if p.get("avr_loss") is not None]
    ok = rc == 0 and final.exists() and bool(losses) and all(l == l and l < 10 for l in losses)
    return {"ok": ok, "rc": rc, "expert": expert, "resolution": f"{ds['w']}x{ds['h']}", "frames": ds["frames"],
            "blocks_to_swap": blocks_to_swap, "fp8": True, "steps": pts[-1]["step"] if pts else 0,
            "s_per_step": round(sorted(steady)[len(steady) // 2], 3) if steady else None,
            "first_avr_loss": losses[0] if losses else None, "last_avr_loss": losses[-1] if losses else None,
            "vram_peak_gb": vram.get("peak_gb"), "lora": str(final) if final.exists() else None,
            "lora_mb": round(final.stat().st_size / 1e6, 1) if final.exists() else None,
            "min_timestep": EXPERTS[expert]["min_t"], "max_timestep": EXPERTS[expert]["max_t"]}


def cmd_check_args(a) -> None:
    """CPU-only sanity check of the trainer arguments: parses the config file + CLI and prints the timestep histogram
    (`--show_timesteps console`) for each expert. Reads only the DiT header; never touches the GPU."""
    w = C.infra()["local_weights"]
    experts = ["high", "low"] if a.expert == "both" else [a.expert]
    cfg_path = Path(a.config) if a.config else default_config_path(Path(C.infra()["data"]["wan_smoke"]) / "clips", 832, 480, 81)
    for e in experts:
        dit = w[EXPERTS[e]["dit"]]
        if not Path(dit).exists():
            dit = w[EXPERTS["high"]["dit"]]  # header check only
        cmd = train_command(e, cfg_path, C.TMP / "check_args", "check", 10, 5, [], dit=dit)
        idx = cmd.index(C.musubi_script("wan_train_network.py"))
        C.run([C.musubi_python(), "-m", "src.train.musubi_cpu", "wan_train_network", *cmd[idx + 1:], "--show_timesteps", "console"],
              env={**C.cpu_env(), "PYTHONPATH": str(C.REPO)}, cwd=str(C.REPO))


# ----------------------------------------------------------------------------- Hub: upload cache, pull LoRA

def cmd_upload_cache(a) -> None:
    ds = load_dataset_config(Path(a.config))
    name = a.name or dataset_name(ds["clips"])
    path_in_repo = f"wan/{name}/{variant_name(ds['w'], ds['h'], ds['frames'])}"
    raw = C.read_toml(Path(a.config))
    # the job rebuilds the dataset TOML from this (paths are replaced by job-local ones; no media path leaves the machine)
    job_ds = {k: v for k, v in raw["datasets"][0].items() if k not in ("video_directory", "cache_directory")}
    meta = {"kind": "wan", "resolution": [ds["w"], ds["h"]], "frames": ds["frames"], "i2v": True,
            "musubi_commit": C.infra()["musubi"]["commit"], "dataset": name,
            "dataset_config": {"general": raw["general"], "dataset": job_ds}}
    C.upload_cache_shards(ds["cache"], path_in_repo, ARCH, meta, shard_gb=a.shard_gb)
    print(f"CACHE_PATH={path_in_repo}")


def cmd_synthetic_cache(a) -> None:
    """Shape-identical random cache for throughput / VRAM probes (no media involved); optionally upload it."""
    w, h = parse_res(a.resolution)
    variant = variant_name(w, h, a.frames)
    out = C.TMP / "synthetic_cache" / variant
    if out.exists():
        for f in out.glob("*.safetensors"):
            f.unlink()
    C.run([C.musubi_python(), "-m", "src.train.synthetic_cache", "--out", str(out), "--n", str(a.n),
           "--resolution", a.resolution, "--frames", str(a.frames)], env={**C.cpu_env(), "PYTHONPATH": str(C.REPO)}, cwd=str(C.REPO))
    if a.upload:
        path_in_repo = f"wan/{a.name}/{variant}"
        meta = {"kind": "wan", "resolution": [w, h], "frames": a.frames, "i2v": True, "synthetic": True,
                "musubi_commit": C.infra()["musubi"]["commit"], "dataset": a.name,
                "dataset_config": {"general": {"resolution": [w, h], "caption_extension": ".txt", "batch_size": 1,
                                               "enable_bucket": False, "bucket_no_upscale": False},
                                   "dataset": {"target_frames": [a.frames], "frame_extraction": "head", "num_repeats": 1}}}
        C.upload_cache_shards(out, path_in_repo, ARCH, meta)
        print(f"CACHE_PATH={path_in_repo}")


def cmd_pull(a) -> None:
    """Download a LoRA checkpoint of a run from the PRIVATE model repo into ComfyUI's lora folder."""
    api = C.hf_api()
    repo = C.infra()["hub"]["lora_repo"]
    from huggingface_hub import hf_hub_download

    prefix = f"runs/{a.run}/"
    files = [f for f in api.list_repo_files(repo, repo_type="model") if f.startswith(prefix) and f.endswith(".safetensors")
             and "/state/" not in f]
    if not files:
        raise SystemExit(f"no checkpoints under {repo}/{prefix}")
    final = f"{prefix}{a.run}.safetensors"
    if a.step is not None:
        target = f"{prefix}{a.run}-step{a.step:08d}.safetensors"
    elif final in files:
        target = final
    else:
        target = sorted(f for f in files if "-step" in f)[-1]
        C.log(f"final checkpoint not found; using the latest step checkpoint {target}")
    if target not in files:
        raise SystemExit(f"{target} not in repo; available: {[f.split('/')[-1] for f in files]}")
    dest = Path(a.dest) if a.dest else C.WORK / "models" / "comfy" / "loras"
    dest.mkdir(parents=True, exist_ok=True)
    p = hf_hub_download(repo, target, repo_type="model", local_dir=str(C.TMP / "pull_lora"), token=os.environ["HF_TOKEN"])
    out = dest / Path(target).name
    import shutil

    shutil.move(p, out)
    C.log(f"LoRA -> {out} ({out.stat().st_size / 1e6:.1f} MB). ComfyUI: LoraLoaderModelOnly, lora_name={out.name}")
    if getattr(a, "convert", False):
        # musubi (kohya-style lora_unet_* keys) -> "other" (diffusers-style diffusion_model.* keys) for loaders that need it
        conv = out.with_name(out.stem + "_diffusers.safetensors")
        C.run([C.musubi_python(), C.musubi_script("convert_lora.py"), "--input", str(out), "--output", str(conv), "--target", "other"],
              env=C.cpu_env())
        C.log(f"converted copy -> {conv}")


# ----------------------------------------------------------------------------- CLI

def main() -> None:
    C.load_env()
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = p.add_subparsers(dest="cmd", required=True)

    s = sub.add_parser("make-smoke-set", help="cut 8 smoke clips from a train episode proxy")
    s.add_argument("--episode", type=int, default=1)
    s.add_argument("--n", type=int, default=8)
    s.add_argument("--out", default=None)
    s.set_defaults(fn=cmd_make_smoke_set)

    s = sub.add_parser("make-config", help="write the musubi dataset TOML for a clips dir")
    s.add_argument("--clips", default=C.infra()["data"]["wan_clips"])
    s.add_argument("--resolution", default="832x480")
    s.add_argument("--frames", type=int, default=81)
    s.add_argument("--batch-size", type=int, default=1)
    s.add_argument("--repeats", type=int, default=1)
    s.add_argument("--cache-dir", default=None)
    s.add_argument("--out", default=None)
    s.add_argument("--probe", type=int, default=20, help="ffprobe this many clips (-1 = all, 0 = none)")
    s.set_defaults(fn=cmd_make_config)

    s = sub.add_parser("cache", help="musubi latent (I2V) + T5 caching")
    s.add_argument("--config", required=True)
    s.add_argument("--device", choices=["cuda", "cpu"], default="cuda")
    s.add_argument("--need-gb", type=int, default=14)
    s.add_argument("--vae-batch-size", type=int, default=1)
    s.add_argument("--te-batch-size", type=int, default=16)
    s.add_argument("--vae-cache-cpu", action="store_true", help="musubi --vae_cache_cpu: less VRAM, slower")
    s.add_argument("--no-skip-existing", dest="skip_existing", action="store_false")
    s.add_argument("--only", choices=["both", "latents", "te"], default="both",
                   help="latents can be cached before the captions exist; the text-encoder cache needs the final captions")
    s.set_defaults(fn=cmd_cache)

    s = sub.add_parser("smoke", help="short local training run for the high/low expert on the 24 GB card")
    s.add_argument("--expert", choices=["high", "low", "both"], default="both")
    s.add_argument("--config", default=None, help="dataset TOML (default: smoke clips at --resolution/--frames)")
    s.add_argument("--resolution", default="416x240")
    s.add_argument("--frames", type=int, default=33)
    s.add_argument("--steps", type=int, default=60)
    s.add_argument("--blocks-to-swap", type=int, default=20)
    s.add_argument("--need-gb", type=int, default=22)
    s.add_argument("--cache-device", choices=["cuda", "cpu"], default="cuda")
    s.add_argument("--recache", action="store_true")
    s.set_defaults(fn=cmd_smoke)

    s = sub.add_parser("check-args", help="CPU-only: validate trainer args and print the timestep histogram per expert")
    s.add_argument("--expert", choices=["high", "low", "both"], default="both")
    s.add_argument("--config", default=None)
    s.set_defaults(fn=cmd_check_args)

