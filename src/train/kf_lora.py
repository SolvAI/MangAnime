"""Keyframe LoRA tooling: Qwen-Image-Edit-2511 (manga panel [+ character reference] -> anime frame), musubi-tuner.

Run with the musubi venv (after `. scripts/env.sh`):

    MP=$KOMI_WORK/venvs/musubi/bin/python
    $MP -m src.train.kf_lora make-smoke-set                       # 8 synthetic pairs from episode 1 (local only)
    $MP -m src.train.kf_lora make-config --root <kf dir>          # metadata JSONL + dataset TOML
    $MP -m src.train.kf_lora cache --config <toml>                # VAE latents (target + controls) + Qwen2.5-VL outputs
    $MP -m src.train.kf_lora smoke                                # ~50 steps on the 24 GB card (fp8 + block swap)
    $MP -m src.train.kf_lora upload-cache --config <toml>         # tar shards -> PRIVATE dataset repo
    $MP -m src.train.kf_lora pull --run <run_name>                # LoRA -> models/comfy/loras/

Dataset contract (<root> = data/processed/train/kf):
    <root>/control/<id>.png        manga panel                      -> control image 0
    <root>/control/<id>_ref.png    optional character reference     -> control image 1
    <root>/target/<id>.png         anime frame (16:9)
    <root>/target/<id>.txt         instruction caption
musubi's directory mode wants numbered control files (<id>_0.png, <id>_1.png), so `make-config` writes a metadata
JSONL (image_path / control_path_0 / control_path_1 / caption) instead of renaming anything.

musubi requirements (docs/qwen_image.md @ f8a1b037): `--model_version edit-2511`; the DiT must be the bf16 file
(qwen_image_edit_2511_bf16.safetensors) and the text encoder qwen_2.5_vl_7b.safetensors: the ComfyUI fp8mixed /
fp8_scaled files used for inference cannot be loaded by the trainer.
"""
from __future__ import annotations

import argparse
import json
import subprocess
import sys
from pathlib import Path

from . import common as C

ARCH = "qie"
MODEL_VERSION = "edit-2511"
TRAIN_CONFIG = "train_kf_qie2511.toml"


def parse_res(s: str) -> tuple[int, int]:
    w, h = (int(x) for x in s.lower().split("x"))
    if w % 16 or h % 16:
        raise SystemExit(f"resolution {s}: width and height must be multiples of 16")
    return w, h


def variant_name(w: int, h: int, cw: int, ch: int) -> str:
    return f"{w}x{h}_c{cw}x{ch}"


def dataset_name(root: Path) -> str:
    return "full" if root.resolve().name == "kf" else root.resolve().name


# ----------------------------------------------------------------------------- dataset config

def collect_pairs(root: Path) -> list[dict]:
    target, control = root / "target", root / "control"
    rows, problems = [], []
    for img in sorted(target.glob("*.png")):
        cid = img.stem
        cap = img.with_suffix(".txt")
        panel = control / f"{cid}.png"
        if not cap.exists():
            problems.append(f"{cid}: missing target/{cid}.txt")
            continue
        if not panel.exists():
            problems.append(f"{cid}: missing control/{cid}.png")
            continue
        row = {"image_path": str(img), "control_path_0": str(panel)}
        ref = control / f"{cid}_ref.png"
        if ref.exists():
            row["control_path_1"] = str(ref)
        row["caption"] = cap.read_text(encoding="utf-8").strip()
        rows.append(row)
    if problems:
        raise SystemExit(f"{len(problems)} broken pairs, e.g.\n  " + "\n  ".join(problems[:8]))
    if not rows:
        raise SystemExit(f"no pairs found under {root} (expected target/<id>.png + control/<id>.png)")
    C.assert_train_split([Path(r["image_path"]).name for r in rows])
    return rows


def cmd_make_config(a) -> Path:
    root = Path(a.root).resolve()
    w, h = parse_res(a.resolution)
    cw, ch = parse_res(a.control_resolution)
    rows = collect_pairs(root)
    variant = variant_name(w, h, cw, ch)
    cfg_dir = root / "configs"
    jsonl = cfg_dir / f"kf_{variant}.jsonl"
    C.write_text(jsonl, "".join(json.dumps(r, ensure_ascii=False) + "\n" for r in rows))
    cache_dir = Path(a.cache_dir).resolve() if a.cache_dir else root / "cache" / f"kf_{variant}"
    out = Path(a.out).resolve() if a.out else cfg_dir / f"kf_{variant}.toml"
    n_ref = sum(1 for r in rows if "control_path_1" in r)
    cfg = {
        "_comment": (f"musubi-tuner dataset config (Qwen-Image-Edit-2511), generated by src/train/kf_lora.py make-config\n"
                     f"root={root}: {len(rows)} pairs, {n_ref} with a character reference (second control image)\n"
                     f"The cache directory must not be shared between datasets/variants."),
        "general": {"resolution": [w, h], "batch_size": a.batch_size, "enable_bucket": True, "bucket_no_upscale": False},
        "datasets": [{"image_jsonl_file": str(jsonl), "cache_directory": str(cache_dir),
                      # docs/dataset_config.md: control_resolution [1024, 1024] = official resizing, strongly recommended
                      "control_resolution": [cw, ch], "no_resize_control": False, "num_repeats": a.repeats}],
    }
    C.write_text(out, C.toml_dump(cfg))
    cache_dir.mkdir(parents=True, exist_ok=True)
    C.log(f"wrote {out} + {jsonl.name}  ({len(rows)} pairs, {n_ref} with reference, cache -> {cache_dir})")
    return out


def load_dataset_config(path: Path) -> dict:
    cfg = C.read_toml(path)
    ds = cfg["datasets"][0]
    w, h = cfg["general"]["resolution"]
    cw, ch = ds["control_resolution"]
    jsonl = Path(ds["image_jsonl_file"])
    n = sum(1 for line in jsonl.read_text(encoding="utf-8").splitlines() if line.strip())
    return {"path": path, "raw": cfg, "jsonl": jsonl, "root": jsonl.parent.parent, "cache": Path(ds["cache_directory"]),
            "w": w, "h": h, "cw": cw, "ch": ch, "n": n}


# ----------------------------------------------------------------------------- smoke set

def cmd_make_smoke_set(a) -> None:
    """8 stand-in pairs from a TRAIN episode proxy: target = anime frame, control = a pseudo 'manga panel' derived from
    it (grayscale + edge emphasis, portrait crop), every second pair also gets a reference crop. Local only."""
    C.assert_train_split([f"ep{a.episode:02d}"])
    src = C.WORK / "data" / "interim" / "anime" / f"ep{a.episode:02d}" / "proxy.mp4"
    if not src.exists():
        raise SystemExit(f"missing {src}")
    root = Path(a.out) if a.out else Path(C.infra()["data"]["kf_smoke"])
    (root / "target").mkdir(parents=True, exist_ok=True)
    (root / "control").mkdir(parents=True, exist_ok=True)
    dur = float(subprocess.run([str(C.FFPROBE), "-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", str(src)],
                               capture_output=True, text=True).stdout.strip())
    ff = [str(C.FFMPEG), "-v", "error", "-y"]
    for i in range(a.n):
        t = 200 + i * (dur - 400) / max(1, a.n - 1)
        cid = f"ep{a.episode:02d}_kfsmoke{i:02d}"
        tgt = root / "target" / f"{cid}.png"
        if not tgt.exists():
            C.run([*ff, "-ss", f"{t:.3f}", "-i", str(src), "-frames:v", "1", "-vf", "crop=832:480", str(tgt)])
        panel = root / "control" / f"{cid}.png"
        if not panel.exists():  # portrait crop, grayscale, edges darkened: a crude panel look-alike
            C.run([*ff, "-i", str(tgt), "-frames:v", "1",
                   "-vf", "crop=352:480:240:0,format=gray,split[a][b];[b]edgedetect=low=0.08:high=0.2,negate[e];[a][e]blend=all_mode=multiply,format=rgb24",
                   str(panel)])
        ref = root / "control" / f"{cid}_ref.png"
        if i % 2 == 0 and not ref.exists():
            C.run([*ff, "-ss", f"{max(0.0, t - 2.0):.3f}", "-i", str(src), "-frames:v", "1", "-vf", "crop=480:480:187:0", str(ref)])
        C.write_text(root / "target" / f"{cid}.txt",
                     "Convert the manga panel into a full-color anime frame in komi_anime_style, 16:9, keeping the characters and composition"
                     + (", using the second image as the character reference.\n" if i % 2 == 0 else ".\n"))
    C.log(f"kf smoke set: {a.n} pairs in {root}")


# ----------------------------------------------------------------------------- caching

def cmd_cache(a) -> None:
    ds = load_dataset_config(Path(a.config))
    w = C.infra()["local_weights"]
    log_file = ds["cache"].parent / "logs" / f"cache_{ds['cache'].name}.log"
    py = C.musubi_python()
    common_args = ["--dataset_config", str(ds["path"]), "--model_version", MODEL_VERSION] + (["--skip_existing"] if a.skip_existing else [])
    te_args = ["--text_encoder", w["qwen_te"], "--batch_size", "1"]
    if a.device == "cpu":
        # GPU untouched (CUDA hidden). The VL text encoder stays bf16 on the CPU: correct but very slow; smoke sets only.
        env = {**C.cpu_env(), "PYTHONPATH": str(C.REPO)}
        C.run([py, "-m", "src.train.musubi_cpu", "qwen_image_cache_latents", *common_args, "--vae", w["qwen_vae"],
               "--device", "cpu", "--vae_dtype", "float32", "--num_workers", "2"], log_file=log_file, env=env, cwd=str(C.REPO))
        C.run([py, "-m", "src.train.musubi_cpu", "qwen_image_cache_text_encoder_outputs", *common_args, *te_args,
               "--device", "cpu", "--num_workers", "2"], log_file=log_file, env=env, cwd=str(C.REPO))
    else:
        C.run([*C.gpu_prefix(a.need_gb), py, C.musubi_script("qwen_image_cache_latents.py"), *common_args, "--vae", w["qwen_vae"]],
              log_file=log_file)
        # bf16 Qwen2.5-VL needs ~17 GB; --fp8-vl brings it under 12 GB when the card is shared
        C.run([*C.gpu_prefix(a.need_gb), py, C.musubi_script("qwen_image_cache_text_encoder_outputs.py"), *common_args, *te_args,
               *(["--fp8_vl"] if a.fp8_vl else [])], log_file=log_file)
    files = C.list_cache_files(ds["cache"], ARCH)
    n_lat = sum(1 for p in files if not p.name.endswith("_te.safetensors"))
    n_te = len(files) - n_lat
    C.log(f"cache: {n_lat} latent + {n_te} text-encoder files for {ds['n']} pairs, "
          f"{sum(p.stat().st_size for p in files) / 1e6:.1f} MB in {ds['cache']}")
    if n_lat != ds["n"] or n_te != ds["n"]:
        raise SystemExit("cache is incomplete (see the log above); re-run `cache`")


# ----------------------------------------------------------------------------- local smoke test

def train_command(dataset_config: Path, out_dir: Path, name: str, steps: int, save_every: int, extra: list[str]) -> list[str]:
    w = C.infra()["local_weights"]
    return [*C.accelerate_launch("bf16"), C.musubi_script("qwen_image_train_network.py"),
            "--config_file", str(C.REPO / "configs" / TRAIN_CONFIG), "--dit", w["qwen_dit"],
            "--dataset_config", str(dataset_config), "--output_dir", str(out_dir), "--output_name", name,
            "--logging_dir", str(out_dir / "tb"), "--max_train_steps", str(steps), "--save_every_n_steps", str(save_every),
            "--save_state", *extra]


def cmd_smoke(a) -> None:
    if a.config:
        cfg_path = Path(a.config)
    else:
        cfg_path = cmd_make_config(argparse.Namespace(root=C.infra()["data"]["kf_smoke"], resolution=a.resolution,
                                                      control_resolution=a.control_resolution, cache_dir=None, out=None,
                                                      batch_size=1, repeats=1))
    ds = load_dataset_config(cfg_path)
    w = C.infra()["local_weights"]
    for k in ("qwen_dit", "qwen_te", "qwen_vae"):
        if not Path(w[k]).exists():
            raise SystemExit(f"missing weight {k}: {w[k]}")
    if not C.list_cache_files(ds["cache"], ARCH) or a.recache:
        cmd_cache(argparse.Namespace(config=str(cfg_path), device="cuda", need_gb=a.need_gb, skip_existing=True, fp8_vl=False))
    # 24 GB settings (docs/qwen_image.md: fp8_scaled + blocks_to_swap 16 = 24 GB at 1024x1024; edit mode needs more)
    extra = ["--fp8_base", "--fp8_scaled", "--blocks_to_swap", str(a.blocks_to_swap), "--lr_warmup_steps", "10"]
    name = "smoke_kf_qie2511"
    out_dir = C.RUNS / "train" / name
    out_dir.mkdir(parents=True, exist_ok=True)
    log_file = out_dir / "train.log"
    if log_file.exists():
        log_file.unlink()
    cmd = train_command(cfg_path, out_dir, name, a.steps, max(1, a.steps // 2), extra)
    rc = C.run([*C.gpu_prefix(a.need_gb), sys.executable, "-m", "src.train.vram_watch", str(out_dir / "vram.json"), "--", *cmd],
               log_file=log_file, check=False, cwd=str(C.REPO), env={"PYTHONPATH": str(C.REPO)})
    from infra.hf_jobs.logparse import parse_progress

    pts = parse_progress(log_file.read_text(errors="replace"))
    steady = sorted(p["s_per_step"] for p in pts if p["step"] >= 3 and p.get("s_per_step"))
    losses = [p["avr_loss"] for p in pts if p.get("avr_loss") is not None]
    vram = {}
    try:
        vram = json.loads((out_dir / "vram.json").read_text())
    except Exception:  # noqa: BLE001
        pass
    final = out_dir / f"{name}.safetensors"
    res = {"ok": rc == 0 and final.exists() and bool(losses) and all(l == l and l < 10 for l in losses), "rc": rc,
           "resolution": f"{ds['w']}x{ds['h']}", "control_resolution": f"{ds['cw']}x{ds['ch']}", "blocks_to_swap": a.blocks_to_swap,
           "fp8": True, "steps": pts[-1]["step"] if pts else 0, "s_per_step": round(steady[len(steady) // 2], 3) if steady else None,
           "first_avr_loss": losses[0] if losses else None, "last_avr_loss": losses[-1] if losses else None,
           "vram_peak_gb": vram.get("peak_gb"), "lora": str(final) if final.exists() else None}
    C.write_text(out_dir / "smoke_result.json", json.dumps(res, indent=1))
    C.log(f"kf smoke: {json.dumps(res)}")
    if not res["ok"]:
        raise SystemExit(f"kf smoke test FAILED (log: {log_file})")


def cmd_check_args(a) -> None:
    """CPU-only: parse the trainer config + CLI and print the timestep histogram (no model is loaded)."""
    cfg_path = Path(a.config) if a.config else Path(C.infra()["data"]["kf_smoke"]) / "configs" / "kf_832x480_c512x512.toml"
    cmd = train_command(cfg_path, C.TMP / "check_args", "check", 10, 5, [])
    idx = cmd.index(C.musubi_script("qwen_image_train_network.py"))
    C.run([C.musubi_python(), "-m", "src.train.musubi_cpu", "qwen_image_train_network", *cmd[idx + 1:], "--show_timesteps", "console"],
          env={**C.cpu_env(), "PYTHONPATH": str(C.REPO)}, cwd=str(C.REPO))


# ----------------------------------------------------------------------------- Hub

def cmd_upload_cache(a) -> None:
    ds = load_dataset_config(Path(a.config))
    name = a.name or dataset_name(ds["root"])
    path_in_repo = f"kf/{name}/{variant_name(ds['w'], ds['h'], ds['cw'], ds['ch'])}"
    raw = ds["raw"]
    job_ds = {k: v for k, v in raw["datasets"][0].items() if k not in ("image_jsonl_file", "cache_directory")}
    meta = {"kind": "kf", "model_version": MODEL_VERSION, "resolution": [ds["w"], ds["h"]], "control_resolution": [ds["cw"], ds["ch"]],
            "musubi_commit": C.infra()["musubi"]["commit"], "dataset": name,
            "dataset_config": {"general": raw["general"], "dataset": job_ds}}
    C.upload_cache_shards(ds["cache"], path_in_repo, ARCH, meta, shard_gb=a.shard_gb)
    print(f"CACHE_PATH={path_in_repo}")


def main() -> None:
    C.load_env()
    from .wan_lora import cmd_pull  # same model repo layout

    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = p.add_subparsers(dest="cmd", required=True)

    s = sub.add_parser("make-smoke-set", help="8 stand-in (panel, frame) pairs from a train episode proxy")
    s.add_argument("--episode", type=int, default=1)
    s.add_argument("--n", type=int, default=8)
    s.add_argument("--out", default=None)
    s.set_defaults(fn=cmd_make_smoke_set)

    s = sub.add_parser("make-config", help="write the metadata JSONL + musubi dataset TOML")
    s.add_argument("--root", default=C.infra()["data"]["kf_root"])
    s.add_argument("--resolution", default="1280x720", help="target bucket resolution (16:9 anime frames)")
    s.add_argument("--control-resolution", default="1024x1024", help="official control resizing: 1024x1024 area")
    s.add_argument("--batch-size", type=int, default=1)
    s.add_argument("--repeats", type=int, default=1)
    s.add_argument("--cache-dir", default=None)
    s.add_argument("--out", default=None)
    s.set_defaults(fn=cmd_make_config)

    s = sub.add_parser("cache", help="musubi latent + Qwen2.5-VL caching (edit-2511)")
    s.add_argument("--config", required=True)
    s.add_argument("--device", choices=["cuda", "cpu"], default="cuda")
    s.add_argument("--need-gb", type=int, default=20)
    s.add_argument("--fp8-vl", action="store_true", help="fp8 text encoder (<16 GB VRAM)")
    s.add_argument("--no-skip-existing", dest="skip_existing", action="store_false")
    s.set_defaults(fn=cmd_cache)

    s = sub.add_parser("smoke", help="short local training run on the 24 GB card")
    s.add_argument("--config", default=None)
    s.add_argument("--resolution", default="832x480")
    s.add_argument("--control-resolution", default="512x512")
    s.add_argument("--steps", type=int, default=50)
    s.add_argument("--blocks-to-swap", type=int, default=30)
    s.add_argument("--need-gb", type=int, default=22)
    s.add_argument("--recache", action="store_true")
    s.set_defaults(fn=cmd_smoke)

    s = sub.add_parser("check-args", help="CPU-only: validate trainer args and print the timestep histogram")
    s.add_argument("--config", default=None)
    s.set_defaults(fn=cmd_check_args)

    s = sub.add_parser("upload-cache", help="upload cache shards to the PRIVATE dataset repo")
    s.add_argument("--config", required=True)
    s.add_argument("--name", default=None)
    s.add_argument("--shard-gb", type=float, default=1.0)
    s.set_defaults(fn=cmd_upload_cache)

    s = sub.add_parser("pull", help="download a trained LoRA into models/comfy/loras/")
    s.add_argument("--run", required=True)
    s.add_argument("--step", type=int, default=None)
    s.add_argument("--dest", default=None)
    s.add_argument("--convert", action="store_true", help="also write a diffusers-format copy (musubi convert_lora.py --target other)")
    s.set_defaults(fn=cmd_pull)

    a = p.parse_args()
    a.fn(a)


if __name__ == "__main__":
    main()
